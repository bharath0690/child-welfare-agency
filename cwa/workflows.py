# Kin: first-contact message, drafted for the worker to review (skill: kin-first-contact)
# ------------------------------------------------------------------------------------------------------
FIRST_CONTACT = {
    "English": ("Hello {name},\n\nMy name is {worker}. I'm a caseworker with Cedar County Child Welfare. I'm reaching out because "
                "{child}, who is part of your family, is being cared for by our agency right now. {child} is safe.\n\n"
                "Family matters a lot to children. You may be able to help, for example by staying in touch, by caring for "
                "{child}, or in other ways that fit your life. There is no pressure to decide anything today.\n\n"
                "Please call or text me at {phone}, or reply to this message. I'm happy to answer your questions.\n\n{worker}"),
    "Spanish": ("Hola {name}:\n\nMe llamo {worker}. Soy trabajador(a) social del Departamento de Bienestar Infantil del Condado de "
                "Cedar. Le escribo porque {child}, que es parte de su familia, está bajo el cuidado de nuestra agencia en este "
                "momento. {child} está a salvo.\n\nLa familia es muy importante para los niños. Usted podría ayudar, por ejemplo, "
                "manteniéndose en contacto, cuidando a {child} o de otras maneras que se ajusten a su vida. No tiene que decidir "
                "nada hoy.\n\nPor favor llámeme o envíeme un mensaje al {phone}, o responda a este mensaje. Con gusto respondo "
                "sus preguntas.\n\n{worker}"),
}


def first_contact(ident, case_id, relationship_id):
    case = gateway.call(ident, "case_get", {"case_id": case_id})
    rel = next((r for r in gateway.call(ident, "relationships_list", {"case_id": case_id}) if r["id"] == int(relationship_id)), None)
    if not rel:
        raise gateway.GatewayError("not_found", "Relative not found on this case.")
    w = db.row("SELECT name, phone FROM workers WHERE id=?", (ident.user_id,))
    lang = rel["language"].split(",")[0].strip()
    vals = dict(name=rel["name"].split()[0], worker=w["name"], phone=w["phone"], child=case["child"]["first"])
    mode, note = "scripted", None
    if lang in FIRST_CONTACT:
        body = FIRST_CONTACT[lang].format(**vals)
    elif llm.enabled():
        try:
            msg = llm.chat([{"role": "system", "content": _skill_prompt("caseworker", "kin-first-contact")},
                            {"role": "user", "content": f"Translate into {lang}, keep it warm and plain:\n\n" + FIRST_CONTACT["English"].format(**vals)}],
                           temperature=0.2)
            body, mode = msg.get("content") or FIRST_CONTACT["English"].format(**vals), "live"
        except llm.LLMError:
            body, lang = FIRST_CONTACT["English"].format(**vals), "English"
            note = f"Translation into {rel['language']} needs live mode or a bilingual colleague. English draft shown."
    else:
        body = FIRST_CONTACT["English"].format(**vals)
        note = f"{rel['name']} prefers {lang}. Scripted mode has English and Spanish only, so a bilingual colleague should translate this."
        lang = "English"
    prop = gateway.call(ident, "outreach_draft", {"case_id": case_id, "relationship_id": rel["id"], "language": lang, "body": body})
    return {"proposal": prop, "to": rel["name"], "relation": rel["relation"], "language": lang, "body": body, "note": note,
            "reading_grade": round(guardrails.reading_grade(body), 1) if lang == "English" else None, "mode": mode,
            "banner": "Agency AI draft. You review and send. Translations need a bilingual check before sending."}


# ------------------------------------------------------------------------------------------------------
# Applicant: inquiry triage (skill: inquiry-triage) and application assistant (skill: application-assistant)
# ------------------------------------------------------------------------------------------------------
def inquiry_triage(name, text, language=None):
    g = guardrails.check_input(text, "applicant")
    t = text.lower()
    intent = ("kinship" if re.search(r"grand|niece|nephew|my (sister|brother)'?s|relative|family member", t) else
              "adoption" if "adopt" in t else "respite" if "respite" in t or "weekend" in t else
              "foster" if re.search(r"foster|license|become", t) else "general question")
    urgency = "urgent: safety" if g["safety"] else "high" if intent == "kinship" else "normal"
    lang = language or ("Spanish" if g["spanish"] else "English")
    routed = "Priya Natarajan (licensing)" if intent in ("foster", "adoption", "respite", "general question") else "Intake duty worker (kin)"
    first = (name or "there").split()[0]
    ack = (f"Thank you, {first}. We got your message. {routed.split(' (')[0]} will contact you within 2 business days. "
           "In the meantime, you can read about the steps to become a foster parent.") if not g["safety"] else \
          (f"Thank you, {first}. Your message mentions a child's safety, so it has gone straight to a person on our team. "
           f"{guardrails.CRISIS_LINE}")
    if lang == "Spanish" and not g["safety"]:
        ack = (f"Gracias, {first}. Recibimos su mensaje. Una persona de nuestro equipo se comunicará con usted en un plazo de "
               "2 días hábiles.")
    db.execute("INSERT INTO inquiries (name, text, language, intent, urgency, routed_to, ack, created_at) VALUES (?,?,?,?,?,?,?,?)",
               (name, text[:2000], lang, intent, urgency, routed, ack, datetime.now().isoformat(timespec="seconds")))
    if g["safety"]:
        db.execute("INSERT INTO escalations (object_type, object_id, persona, user_id, text, routed_to, status, created_at) "
                   "VALUES ('inquiry','-','applicant','public',?,?, 'open', ?)",
                   (text[:2000], "Intake duty worker", datetime.now().isoformat(timespec="seconds")))
    return {"intent": intent, "urgency": urgency, "language": lang, "routed_to": routed, "acknowledgement": ack, "mode": "rules"}


FIELD_LABELS = {"home_description": "Describe your home", "why_foster": "Why do you want to foster?",
                "support_network": "Who supports your family?", "years_at_address": "How long have you lived at this address?"}


def application_help(ident, field, notes):
    if field not in FIELD_LABELS:
        raise gateway.GatewayError("bad_field", "Pick a narrative field.")
    notes = (notes or "").strip()
    if not notes:
        return {"error": "Write a few words of your own first. Agency AI drafts from your words, not from nothing."}
    mode, text = "scripted", None
    if llm.enabled():
        try:
            msg = llm.chat([{"role": "system", "content": _skill_prompt("applicant", "application-assistant")},
                            {"role": "user", "content": f"Question: {FIELD_LABELS[field]}\nMy notes: {notes}"}],
                           temperature=0.4, max_tokens=400)
            text, mode = (msg.get("content") or "").strip() or None, "live"
        except llm.LLMError:
            text = None
    if not text:
        parts = [p.strip().rstrip(".") for p in re.split(r"[,;\n]|\band\b", notes) if p.strip()]
        lead = {"home_description": "Our home", "why_foster": "We want to foster because",
                "support_network": "Our support network includes", "years_at_address": "We have lived here"}[field]
        body = ", ".join(parts)
        text = f"{lead} {body[0].lower() + body[1:] if body else ''}." if not body.lower().startswith(lead.lower()) else body + "."
    prop = gateway.call(ident, "application_field_draft", {"field": field, "value": text})
    return {"proposal": prop, "field": field, "label": FIELD_LABELS[field], "draft": text, "mode": mode,
            "banner": "Agency AI draft from your own notes. Edit it so it sounds like you, then submit."}


# ------------------------------------------------------------------------------------------------------
# Caseworker: court report assembly (skill: court-report-assembly). Cited facts only; the worker writes
# the recommendation. Moved to Phase 1 because report prep is one of the heaviest documentation loads.
# ------------------------------------------------------------------------------------------------------
def court_report(ident, case_id, hearing_date):
    g = lambda t, **k: gateway.call(ident, t, {"case_id": case_id, **k})
    c = g("case_get")
    hearing = next((h for h in g("court_dates_list") if h["on_date"] == hearing_date), None)
    if not hearing:
        raise gateway.GatewayError("not_found", "No hearing on that date for this case.")
    ch, p = c["child"], c.get("placement") or {}
    visits = g("visits_list")
    notes = db.rows("SELECT on_date, body FROM notes WHERE case_id=? AND status='signed' ORDER BY on_date DESC LIMIT 3", (case_id,))
    plan, refs, rels = g("plan_get"), g("referrals_list"), g("relationships_list")
    reached = [r for r in rels if r["contact_status"] == "Successfully Contacted"]
    lines = [f"COURT REPORT DRAFT: {hearing['hearing']}, {hearing['on_date']}",
             f"Child: {ch['name']}, age {ch['age']}. Case {c['case_no']}. Worker: {c['worker']}. (Source: case record)", "",
             "1. Placement",
             f"- Placed with {p.get('caregiver', 'not recorded')} ({p.get('kind', '')}) since {p.get('start_on', '')}. (Source: placements)", "",
             "2. Visits since the last hearing"]
    lines += [f"- {v['on_date']}: {v['kind']} at {v['location']}, note {v['note_status']}. (Source: visit log)" for v in visits[:4]] or ["- None recorded."]
    if notes:
        lines += ["", "3. From signed visit notes"]
        lines += [f"- {n['on_date']}: {n['body'][:220].strip()}{'...' if len(n['body']) > 220 else ''} (Source: signed note {n['on_date']})" for n in notes]
    lines += ["", "4. Case plan progress"]
    lines += [f"- {gl['goal']}: {gl['status']}. (Source: case plan)" for gl in plan] or ["- No agreed plan yet."]
    lines += ["", "5. Services and referrals"]
    lines += [f"- {r['provider']}, {r['service']}: {r['status']}" + (f", sent {r['sent_on']}" if r["sent_on"] else "") + ". (Source: referral log)" for r in refs] or ["- None."]
    lines += ["", "6. Efforts to find and engage relatives",
              f"- {len(reached)} of {len(rels)} identified relatives reached. (Source: relationships)"]
    lines += [f"- {r['name']} ({r['relation']}): {r['contact_status']}" + (f", last contact {r['last_contact_on']}" if r["last_contact_on"] else "") + ". (Source: relationships)" for r in rels]
    lines += ["", "7. Recommendation",
              "[Written by the caseworker. Agency AI does not draft recommendations on placement, custody or reunification.]"]
    body = "\n".join(lines)
    prop = gateway.call(ident, "court_report_draft", {"case_id": case_id, "hearing_date": hearing_date, "body": body})
    return {"proposal": prop, "body": body, "mode": "rules",
            "banner": "Agency AI draft of cited facts. Check each line, write the recommendation, then sign."}


def caseworker_workload(ident):
    """Workload view for the caseworker home: what is on the worker's plate, from telemetry and rules (no model)."""
    rows = [stages.list_row(ident, c["case_id"]) for c in gateway.call(ident, "cases_list_assigned")]
    today = date.today()
    due_week = sum(1 for r in rows if r["next_due"] and 0 <= (date.fromisoformat(r["next_due"]) - today).days <= 7)
    overdue = sum(1 for r in rows if "Overdue task" in r["flags"] or "Visit overdue" in r["flags"])
    drafts = db.row("SELECT COUNT(*) n FROM proposals p JOIN cases c ON c.id=p.object_id WHERE p.object_type='case' AND p.status='pending' "
                    "AND c.worker_id=?", (ident.user_id,))["n"]
    court = sum(1 for r in rows if "Court soon" in r["flags"])
    recog = db.rows("SELECT from_name, case_id, text, on_date FROM recognitions WHERE worker_id=? ORDER BY on_date DESC LIMIT 2", (ident.user_id,))
    return {"cases": len(rows), "recommended": 12, "due_this_week": due_week, "overdue": overdue, "drafts_to_sign": drafts,
            "court_within_14": court, "recognition": recog,
            "note": "Recommended caseload of about 12 is from national guidance cited in public reporting. Counts come from case data, not a model."}
