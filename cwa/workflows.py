"""Fixed-step workflows (architecture section 1: "if you can write the steps down, it is a workflow").

Each workflow reads through the gateway, optionally asks the model to word a draft, runs guardrails,
and ends in a proposal a human approves. With no API key, deterministic drafting is used instead.
"""
import json
import re
from datetime import date, datetime

from . import db, gateway, guardrails, llm, skills, stages

LINE = re.compile(r"^\[(\d\d:\d\d)\]\s+([^:]+):\s+(.*)$")


def _lines(transcript):
    out = []
    for raw in (transcript or "").splitlines():
        m = LINE.match(raw.strip())
        if m:
            out.append({"ts": m.group(1), "speaker": m.group(2).strip(), "text": m.group(3).strip()})
    return out


def _skill_prompt(persona, name):
    return skills.load(persona, name).get("instructions", "")


# ------------------------------------------------------------------------------------------------------
# Caseworker: start-of-day briefing (skill: day-briefing)
# ------------------------------------------------------------------------------------------------------
def briefing(ident):
    if ident.persona != "caseworker":
        raise gateway.GatewayError("not_allowed", "The day briefing is for caseworkers.")
    cases = gateway.call(ident, "cases_list_assigned")
    items, rows = [], []
    for c in cases:
        row = stages.list_row(ident, c["case_id"])
        rows.append(row)
        top = stages.refresh(ident, c["case_id"])["actions"][:2]
        for a in top:
            score = a["score"] + (20 if a["pinned"] else 0)
            level = "urgent" if score >= 85 or a["title"].startswith("Overdue") or "overdue" in a["title"] else \
                "soon" if score >= 60 else "routine"
            items.append({"case_id": c["case_id"], "case_no": row["case_no"], "child": row["child"], "avatar_svg": row["avatar_svg"],
                          "title": a["title"], "why": a["why"], "score": score, "level": level, "source": a["source"],
                          "prompt": f"Help me with {row['child'].split()[0]}'s case: {a['title'][0].lower() + a['title'][1:]}"})
    items.sort(key=lambda x: -x["score"])
    signed_ai = db.row("SELECT COUNT(*) n FROM notes n JOIN cases c ON c.id=n.case_id WHERE c.worker_id=? AND n.ai_drafted=1",
                       (ident.user_id,))["n"]
    first = ident.name.split()[0]
    court = [r for r in rows if "Court soon" in r["flags"]]
    summary = (f"Good morning, {first}. You have {len(rows)} cases. "
               + (f"{len(court)} {'has' if len(court) == 1 else 'have'} court within two weeks. " if court else "")
               + (f"Start with {items[0]['child']}: {items[0]['title'].lower()}." if items else "Nothing urgent today."))
    return {"summary": summary, "items": items[:8], "cases": len(rows),
            "time_back": {"ai_notes_signed": signed_ai, "minutes": signed_ai * 25,
                          "note": "Computed from product telemetry (signed AI-drafted notes x 25 min baseline, illustrative), not generated by a model."},
            "mode": "rules"}


# ------------------------------------------------------------------------------------------------------
# Caseworker: visit capture -> note draft (skill: visit-capture)
# ------------------------------------------------------------------------------------------------------
SECTIONS = [
    ("Health", r"health|inhaler|asthma|dentist|sleep|headache|doctor|check-up|glasses|eye|medic"),
    ("School", r"school|grade|class|test|attend|tutor|robotics|reading|teacher"),
    ("Family time", r"\bmom\b|mamá|\bdad\b|grandma|grandpa|aunt|t[ií]a|visits?\b|call (my|your)|phone call"),
    ("Services", r"counsel|referral|program|bright path|therapy|tutoring|kinship guide"),
]


def _draft_note_rules(visit, lines):
    alone_idx = next((i for i, l in enumerate(lines) if re.search(r"alone|on our own|on your own|talk with \w+ for a minute", l["text"], re.I)), None)
    out = [f"{visit['kind']} at {visit['location']} on {visit['on_date']}."]
    out.append("Child seen alone: " + ("yes [" + lines[alone_idx]["ts"] + "]." if alone_idx is not None else "not recorded in the transcript."))
    used = set()
    for title, pat in SECTIONS:
        hits = [l for i, l in enumerate(lines) if i not in used and not l["speaker"].startswith("Worker") and re.search(pat, l["text"], re.I)]
        if hits:
            out.append(f"\n{title}:")
            for l in hits[:3]:
                used.add(lines.index(l))
                out.append(f"- {l['speaker']} said: \"{l['text']}\" [{l['ts']}]")
    if alone_idx is not None:
        views = [l for l in lines[alone_idx + 1:] if l["speaker"].startswith("Child") and lines.index(l) not in used]
        if views:
            out.append("\nChild's views (seen alone):")
            out += [f"- \"{l['text']}\" [{l['ts']}]" for l in views[:3]]
    nxt = [l for l in lines if l["speaker"].startswith("Worker") and re.search(r"I'll|next visit", l["text"], re.I)]
    if nxt:
        out.append("\nNext steps:")
        out += [f"- {l['text']} [{l['ts']}]" for l in nxt]
    return "\n".join(out)


def visit_note(ident, case_id, visit_id):
    v = gateway.call(ident, "visit_get", {"case_id": case_id, "visit_id": int(visit_id)})
    if not v.get("transcript"):
        return {"error": v.get("consent_note") or "This visit has no recording to draft from. Write the note manually."}
    lines = _lines(v["transcript"])
    mode, body = "scripted", None
    if llm.enabled():
        try:
            msg = llm.chat([
                {"role": "system", "content": _skill_prompt("caseworker", "visit-capture")},
                {"role": "user", "content": f"Visit: {v['kind']} at {v['location']} on {v['on_date']}.\nTranscript:\n{v['transcript']}"}],
                temperature=0.2, max_tokens=900)
            body, mode = (msg.get("content") or "").strip() or None, "live"
        except llm.LLMError:
            body = None
    body = body or _draft_note_rules(v, lines)
    findings = guardrails.language_check(body)
    prop = gateway.call(ident, "note_draft", {"case_id": case_id, "visit_id": int(visit_id), "body": body})
    return {"proposal": prop, "body": body, "language_findings": findings, "mode": mode,
            "banner": "Agency AI draft. Review, edit and sign. Each line cites the transcript time."}


# ------------------------------------------------------------------------------------------------------
# Caseworker: form pre-fill with provenance (skill: form-prefill)
# ------------------------------------------------------------------------------------------------------
FORM = "Monthly caseworker visit form"


def _find(lines, pat, speaker=None, used=None):
    for l in lines:
        if used is not None and l["ts"] in used:
            continue
        if (speaker is None or l["speaker"].startswith(speaker)) and re.search(pat, l["text"], re.I):
            if used is not None:
                used.add(l["ts"])
            return l
    return None


def prefill(ident, case_id, visit_id):
    v = gateway.call(ident, "visit_get", {"case_id": case_id, "visit_id": int(visit_id)})
    if not v.get("transcript"):
        return {"error": v.get("consent_note") or "No recording to pre-fill from."}
    L = _lines(v["transcript"])
    f = lambda val, l, conf: {"value": val, "quote": l["text"] if l else None, "ts": l["ts"] if l else None,
                              "source": f"Transcript {v['on_date']}" + (f" {l['ts']}" if l else ""), "confidence": conf}
    speakers = sorted({l["speaker"] for l in L})
    alone = _find(L, r"alone|on our own|on your own|for a minute")
    consent = _find(L, r"record")
    used = set()
    school = _find(L, r"school|grade|attend|test|reading", "C", used)
    health = _find(L, r"inhaler|asthma|dentist|headache|sleep|check-up|health", "C", used)
    safe = _find(L, r"\bsafe\b|like it here|I'm okay here|like t[ií]a", "Child", used)
    services = _find(L, r"counsel|referral|tutor|program|guide", None, used)
    nxt = _find(L, r"next visit", "Worker")
    fields = {
        "visit_date": {"value": v["on_date"], "quote": None, "ts": None, "source": "Visit log", "confidence": "high"},
        "location": {"value": v["location"], "quote": None, "ts": None, "source": "Visit log", "confidence": "high"},
        "persons_present": {"value": ", ".join(speakers), "quote": None, "ts": None, "source": "Transcript speaker labels", "confidence": "high"},
        "recording_consent": f("Yes" if consent else "Not recorded", consent, "high" if consent else "low"),
        "child_seen_alone": f("Yes" if alone else "Not recorded", alone, "high" if alone else "low"),
        "school_update": f(school["text"] if school else "", school, "medium" if school else "low"),
        "health_update": f(health["text"] if health else "", health, "medium" if health else "low"),
        "child_reports_feeling_safe": f("Child said they feel safe or settled" if safe else "Not discussed in transcript", safe,
                                        "medium" if safe else "low"),
        "services_discussed": f(services["text"] if services else "", services, "medium" if services else "low"),
        "next_visit": f(nxt["text"] if nxt else "", nxt, "high" if nxt else "low"),
    }
    prop = gateway.call(ident, "form_prefill_draft", {"case_id": case_id, "visit_id": int(visit_id), "form_type": FORM, "fields": fields})
    return {"proposal": prop, "form_type": FORM, "fields": fields, "mode": "rules",
            "banner": "Agency AI pre-fill. Each field shows its source quote and confidence. Low-confidence fields need your input."}


# ------------------------------------------------------------------------------------------------------
# Caseworker: language and bias check (skill: language-check)
# ------------------------------------------------------------------------------------------------------
def language_check(text):
    findings = guardrails.language_check(text)
    return {"findings": findings, "count": len(findings),
            "note": "Suggestions only. You decide what to change. Ground any rewrite in what was actually said or seen."}


